    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
try {
        int taskId = Integer.parseInt(txtTaskId.getText());
        
        // Confirm before deleting
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete Task " + taskId + "?", "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            if (taskDAO.deleteTask(taskId)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Task Deleted Successfully!");
                // Clear the form
                txtTaskId.setText("");
                txtTaskTitle.setText("");
                cmbStatus.setSelectedIndex(0);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to delete. Task might not exist.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid input! Task ID must be a whole number.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

