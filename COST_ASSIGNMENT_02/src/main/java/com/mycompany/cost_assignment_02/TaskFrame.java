    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
try {
        int taskId = Integer.parseInt(txtTaskId.getText());
        String taskTitle = txtTaskTitle.getText();
        String status = cmbStatus.getSelectedItem().toString();

        Task updatedTask = new Task(taskId, taskTitle, status);
        
        if (taskDAO.updateTask(updatedTask)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Task Updated Successfully!");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to update. Make sure the task exists.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid input! Task ID must be a whole number.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
try {
        // Read and convert Task ID
        int taskId = Integer.parseInt(txtTaskId.getText());
        String taskTitle = txtTaskTitle.getText();
        String status = cmbStatus.getSelectedItem().toString();

        // Create Task object and pass to DAO
        Task newTask = new Task(taskId, taskTitle, status);
        
        if (taskDAO.addTask(newTask)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Task Added Successfully!");
            // Automatically clear the form after adding
            txtTaskId.setText("");
            txtTaskTitle.setText("");
            cmbStatus.setSelectedIndex(0);
        } else {
            // Handles if ID already exists or DB error occurs
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to add task. Make sure the Task ID is unique.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        // Question 5: Handle non-numeric input safely
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid input! Task ID must be a whole number.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
try {
        int taskId = Integer.parseInt(txtTaskId.getText());
        
        // Call DAO search method
        Task foundTask = taskDAO.searchTask(taskId);
        
        if (foundTask != null) {
            // Populate fields if found
            txtTaskTitle.setText(foundTask.getTaskTitle());
            cmbStatus.setSelectedItem(foundTask.getStatus());
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Task not found for ID: " + taskId, "Not Found", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid input! Task ID must be a whole number to search.", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed

